/** Rôles qu'un utilisateur peut attribuer : seul un propriétaire peut nommer un propriétaire. */
export function assignableRoles(actorRole: Role): Role[] {
  const all = Object.keys(DEFAULT_ROLE_PERMISSIONS) as Role[];
  return actorRole === "OWNER" ? all : all.filter((r) => r !== "OWNER");
}

export function resolvePermissions(
  role: Role,
  overrides: { permission: string; granted: boolean }[] = [],
): Set<Permission> {
  const set = new Set<Permission>(DEFAULT_ROLE_PERMISSIONS[role]);
  // Le propriétaire conserve toujours tous les droits (évite de se verrouiller hors de l'organisation)
  if (role === "OWNER") return new Set(ALL);
  for (const o of overrides) {
    if (!(PERMISSIONS as readonly string[]).includes(o.permission)) continue;
    const perm = o.permission as Permission;
    if (o.granted) set.add(perm);
    else set.delete(perm);
  }
  return set;
}

export function isPermission(value: string): value is Permission {
  return (PERMISSIONS as readonly string[]).includes(value);
}
